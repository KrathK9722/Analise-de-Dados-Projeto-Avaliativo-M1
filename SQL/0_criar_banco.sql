-- TABELA SILVER COM DADOS SEPARADOS CORRETAMENTE A TIPAGEM
CREATE TABLE IF NOT EXISTS silver_viagem (
    id_viagem VARCHAR(20) PRIMARY KEY,
    num_proposta VARCHAR(20),
    situacao VARCHAR(50),
    viagem_urgente VARCHAR(5),
    cod_orgao_superior VARCHAR(20),
    nome_orgao_superior VARCHAR(255) NOT NULL,
    nome_viajante VARCHAR(255),
    cargo VARCHAR(255),
    data_inicio DATE,
    data_fim DATE,
    destinos VARCHAR(4000),
    motivo VARCHAR(4000),
    valor_diarias DECIMAL(10,2),
    valor_passagens DECIMAL(10,2),
    valor_devolucao DECIMAL(10,2),
    valor_outros_gastos DECIMAL(10,2),
    valor_total DECIMAL(12,2),
    duracao_dias INT,
    CONSTRAINT ck_viagem_diarias CHECK (valor_diarias >= 0)
);
CREATE TABLE IF NOT EXISTS silver_pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    num_proposta VARCHAR(20),
    nome_orgao_pagador VARCHAR(255),
    nome_ug_pagadora VARCHAR(255),
    tipo_pagamento VARCHAR(50) NOT NULL,
    valor DECIMAL(10,2),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);
CREATE TABLE IF NOT EXISTS silver_passagem (
    id_passagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    meio_transporte VARCHAR(50),
    pais_origem_ida VARCHAR(60),
    uf_origem_ida VARCHAR(40),
    cidade_origem_ida VARCHAR(80),
    pais_destino_ida VARCHAR(60),
    uf_destino_ida VARCHAR(40),
    cidade_destino_ida VARCHAR(80),
    valor_passagem DECIMAL(10,2),
    taxa_servico DECIMAL(10,2),
    data_emissao DATE,
    CONSTRAINT ck_passagem_valor CHECK (valor_passagem >= 0),
    CONSTRAINT ck_passagem_taxa CHECK (taxa_servico >= 0)
);
CREATE TABLE IF NOT EXISTS silver_trecho (
    id_trecho INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    sequencia_trecho INT,
    origem_data DATE,
    origem_uf VARCHAR(40),
    origem_cidade VARCHAR(80),
    destino_data DATE,
    destino_uf VARCHAR(40),
    destino_cidade VARCHAR(80),
    meio_transporte VARCHAR(50),
    numero_diarias DECIMAL(10,2),
    CONSTRAINT ck_trecho_diarias CHECK (numero_diarias >= 0),
    CONSTRAINT uq_trecho_viagem_seq UNIQUE(id_viagem, sequencia_trecho)
);
